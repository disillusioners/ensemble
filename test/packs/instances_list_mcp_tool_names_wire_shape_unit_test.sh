WT = os.environ["WT_UNDER_TEST"]

KEY = "mcp_tool_names"
WITH_ID = "sonic-wire-with-tools"
WITHOUT_ID = "sonic-wire-no-tools"
TOOLS = ["mcp_alpha", "mcp_beta", "mcp_gamma"]


class _Manager:
    """Minimal manager stand-in — the instances router touches only these."""

    def __init__(self, engine):
        self._engine = engine
        self._instance_ui_prefs_repo = InstanceUiPrefsRepository(engine=engine)

    @property
    def is_write_paused(self) -> bool:
        return False

    @staticmethod
    def _row(row: Instance) -> dict:
        return {
            "instance_id": row.instance_id,
            "agent_id": row.agent_id,
            "agent_tag": None,
            "agent_dir": row.agent_dir,
            "status": row.status,
            "parent_id": row.parent_id,
            "title": row.title,
            "initiative_message": row.initiative_message,
            "children": [],
            "metadata": dict(row.instance_metadata or {}),
            "created_at": row.created_at,
            "updated_at": row.updated_at,
            "project_id": row.project_id,
        }

    def list_instances(
        self,
        limit: int = 10,
        offset: int = 0,
        project_id: str | None = None,
        exclude_kb: bool = True,
        include_descendants: bool = False,
        search: str | None = None,
        order: str = "pinned",
        source: str | None = None,
    ):
        with Session(self._engine) as s:
            rows = s.exec(select(Instance).order_by(Instance.created_at)).all()
        return [self._row(r) for r in rows], len(rows), False

    def get_instance_info(self, instance_id: str) -> dict:
        with Session(self._engine) as s:
            row = s.get(Instance, instance_id)
        if row is None:
            raise KeyError(instance_id)
        return self._row(row)

    async def get_queue_stats(self, instance_id: str) -> dict:
        return {}


