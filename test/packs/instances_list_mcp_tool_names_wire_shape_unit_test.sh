def test_pack_runs_against_the_tree_under_test():
    """The pack must exercise TREE's code, not an installed copy."""
    import daemon

    assert daemon.__file__.startswith(WT), (
        f"daemon resolved to {daemon.__file__}, expected under {WT}"
    )


def test_list_rows_omit_the_key_entirely(client):
    """LIST rows carry NO ``mcp_tool_names`` key — not even ``null``."""
    response = client.get("/api/instances")
    assert response.status_code == 200, response.text
    rows = response.json()["instances"]
    assert rows, "expected the seeded rows to be returned"
    ids = {row["instance_id"] for row in rows}
    assert WITH_ID in ids and WITHOUT_ID in ids, ids
    for row in rows:
        assert KEY not in row, (
            f"LIST row {row['instance_id']} carries {KEY}={row.get(KEY)!r}"
        )
    # the RAW payload must not carry the key anywhere
    assert f'"{KEY}"'.encode() not in response.content, response.content[:400]


def test_list_envelope_is_intact(client):
    """The exclude must not leak into the response envelope."""
    response = client.get("/api/instances")
    assert response.status_code == 200, response.text
    body = response.json()
    for envelope_key in ("total", "limit", "offset", "has_more", "truncated"):
        assert envelope_key in body, f"envelope key {envelope_key!r} missing"
    assert body["total"] == 2
    assert isinstance(body["has_more"], bool)
    assert isinstance(body["truncated"], bool)


def test_detail_route_keeps_the_key_populated(client):
    """DETAIL of the seeded row keeps the key, populated."""
    response = client.get(f"/api/instances/{WITH_ID}")
    assert response.status_code == 200, response.text
    body = response.json()
    assert KEY in body, "the DETAIL route must keep the mcp_tool_names key"
    assert body[KEY] == TOOLS, body.get(KEY)


def test_detail_route_keeps_the_key_null_when_metadata_lacks_it(client):
    """DETAIL keeps the key (null) when the metadata carries none."""
    response = client.get(f"/api/instances/{WITHOUT_ID}")
    assert response.status_code == 200, response.text
    body = response.json()
    assert KEY in body, (
        "the DETAIL route must keep the key even when the metadata has none"
    )
    assert body[KEY] is None
