#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# instances_list_mcp_tool_names_wire_shape_unit_test.sh
#
# Independent (sonic-tester) wire-shape gate for the instances-list Option A
# commission:
#   * GET /api/instances        (LIST)   -> rows carry NO "mcp_tool_names" key
#                                           (key-ABSENT; a null value FAILS)
#   * GET /api/instances/{id}   (DETAIL) -> the key is PRESENT and populated
#
# WHY THIS PACK EXISTS (independence, not duplication):
#   the deliverable's own pack (tests/api/test_instances_list_mcp_tool_names.py)
#   drives the app through httpx.AsyncClient + ASGITransport. This gate is a
#   DELIBERATELY INDEPENDENT re-implementation of the same contract on a
#   DIFFERENT transport (fastapi.testclient.TestClient, synchronous, per-request
#   portal) with its own fixtures, so a harness bug in one cannot mask the
#   other. It also asserts the RAW response BYTES (not only the parsed JSON)
#   carry no key anywhere.
#
# USAGE:
#   bash test/packs/instances_list_mcp_tool_names_wire_shape_unit_test.sh [TREE]
#   (TREE defaults to $PWD; it must contain .venv/bin/python — run
#    `uv sync --frozen` there first). The pack runs AGAINST TREE, whatever
#    tree that is; the tree identity is asserted inside the pack.
#
# FENCES: hermetic — in-memory SQLite only; NO postgres, NO live daemon, NO
#   live install dir, NO network, NO ambient DB env consulted. The
#   daemon.services.db_offload seam is replaced by an inline passthrough: it
#   is an execution-detail wrapper (a worker-thread bridge) and does not
#   influence the wire shape; replacing it keeps the pack loop-agnostic.
# ---------------------------------------------------------------------------
set -euo pipefail

WT="${1:-$(pwd)}"
WT="$(cd "$WT" && pwd)"
PY="$WT/.venv/bin/python"
if [ ! -x "$PY" ]; then
  echo "FATAL: no interpreter at $PY (run 'uv sync --frozen' in the tree under test)" >&2
  exit 2
fi

SCRATCH="$(mktemp -d "${TMPDIR:-/tmp}/sonic-ilnames-wire-XXXXXXXX")"
trap 'rm -rf "$SCRATCH"' EXIT

cat > "$SCRATCH/test_instances_list_wire_shape_sonic.py" <<'PYFILE'
"""Independent wire-shape assertions for the GET /api/instances LIST rows.

sonic-tester verification wave, 2026-11-19 (Option A: drop
``mcp_tool_names`` from the LIST wire shape).  Generated by
``test/packs/instances_list_mcp_tool_names_wire_shape_unit_test.sh``.

Contract under test:
  * LIST   (GET /api/instances)      -> rows carry NO ``mcp_tool_names`` key
                                         (key-ABSENT; ``null`` is a FAILURE)
  * DETAIL (GET /api/instances/{id}) -> the key is PRESENT and populated
"""

from __future__ import annotations

import os
from datetime import datetime, timezone

import pytest
from fastapi.testclient import TestClient
from sqlalchemy.pool import StaticPool
from sqlmodel import Session, SQLModel, create_engine, select

