"""Vocabulary freeze cross-checks (metrics-collection P0, T6).

Catalog §8 rule **A1**: every closed vocabulary is DERIVED FROM CODE,
never hand-listed.  Each frozen set is pinned to its runtime source and
cross-checked here — a drift in the source breaks the test (and requires
a ``VOCABULARY_VERSION`` bump, the F0.4/A24 bump contract).

Frozen sets (all in ``daemon/checkpoint_metrics.py``):

* instance status (10) — ``daemon/repositories/instance/models.py``
  → ``InstanceStatus``;
* sweep lane (13) — the seven RDRS lanes (named by the
  ``report_delivery_recovery_lane_*`` kill-switchs of
  ``daemon/config.py``) PLUS the six standalone sweep services (each
  owns a ``DEFAULT_*_INTERVAL_SECONDS`` constant);
* MCP roster (5) — the built-in MCP server registry
  (``daemon/mcp/builtin_servers``) plus ``custom`` + reserved
  ``other``;
* tool category (V-4 artifact) — generated by
  ``tests/unit/tools/test_tool_category_artifact.py``, never hand
  listed.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from daemon import checkpoint_metrics as cm
from daemon.checkpoint_metrics import (
    INSTANCE_STATUS_VOCABULARY,
    MCP_ROSTER_VOCABULARY,
    RESERVED_LABEL_VALUE,
    SWEEP_LANE_VOCABULARY,
    VERSION_LABEL_POLICY,
    VOCABULARY_VERSION,
    render_metrics,
)


class TestInstanceStatusVocabulary:
    """10 values, derived from the ``InstanceStatus`` enum."""

    def test_matches_the_runtime_enum(self) -> None:
        from daemon.repositories.instance.models import InstanceStatus

        derived = {member.value for member in InstanceStatus}
        assert set(INSTANCE_STATUS_VOCABULARY) == derived

    def test_has_ten_values(self) -> None:
        assert len(INSTANCE_STATUS_VOCABULARY) == 10

    def test_covers_the_documented_axis(self) -> None:
        assert {
            "idle",
            "running",
            "waiting",
            "paused",
            "completed",
            "error",
            "terminated",
            "queued",
            "waiting_children",
            "failed",
        } == set(INSTANCE_STATUS_VOCABULARY)


class TestSweepLaneVocabulary:
    """13 lanes = 7 RDRS lanes + 6 standalone sweep services."""

    def test_has_thirteen_values(self) -> None:
        assert len(SWEEP_LANE_VOCABULARY) == 13

    def test_rdrs_lanes_come_from_the_config_kill_switchs(self) -> None:
        import daemon.config as config

        lane_fields = [
            name
            for name in config.ServicesConfig.model_fields
            if name.startswith("report_delivery_recovery_lane_")
        ]
        assert len(lane_fields) == 7, f"RDRS lane count drifted: {sorted(lane_fields)}"
        derived = {
            "rdrs_" + name[len("report_delivery_recovery_lane_") :] for name in lane_fields
        }
        assert derived <= set(SWEEP_LANE_VOCABULARY)

    def test_standalone_sweep_services_are_counted(self) -> None:
        """A count of only the RDRS lanes would drop six series."""
        standalone = {
            name for name in SWEEP_LANE_VOCABULARY if not name.startswith("rdrs_")
        }
        assert len(standalone) == 6

    def test_standalone_lanes_match_the_sweep_services(self) -> None:
        import daemon.services as services_pkg

        services_dir = Path(services_pkg.__file__).resolve().parent
        derived = set()
        for path in sorted(services_dir.glob("*_sweep.py")):
            text = path.read_text(encoding="utf-8")
            if "DEFAULT_" in text and "INTERVAL_SECONDS" in text:
                derived.add(path.stem[: -len("_sweep")])
        frozen = {name for name in SWEEP_LANE_VOCABULARY if not name.startswith("rdrs_")}
        assert derived == frozen, (
            f"standalone sweep lanes drifted: derived={sorted(derived)} frozen={sorted(frozen)}"
        )


class TestMcpRosterVocabulary:
    """5 values: three built-ins + ``custom`` + reserved ``other``."""

    def test_builtins_come_from_the_builtin_registry(self) -> None:
        from daemon.mcp.builtin_servers import get_registry

        builtin_names = {definition.name for definition in get_registry().get_all()}
        assert builtin_names == {"context7", "plane", "webfetch"}
        assert builtin_names <= set(MCP_ROSTER_VOCABULARY)

    def test_has_five_values_with_the_reserved_bucket(self) -> None:
        assert len(MCP_ROSTER_VOCABULARY) == 5
        assert RESERVED_LABEL_VALUE in MCP_ROSTER_VOCABULARY
        assert "custom" in MCP_ROSTER_VOCABULARY


class TestToolCategoryVocabulary:
    """The tool-category set comes from the V-4 generated artifact."""

    def test_is_derived_and_carries_the_reserved_bucket(self) -> None:
        vocabulary = cm.tool_category_vocabulary()
        assert RESERVED_LABEL_VALUE in vocabulary
        assert len(vocabulary) >= 2

    def test_the_artifact_is_committed(self) -> None:
        path = cm.tool_category_artifact_path()
        assert path.is_file(), f"missing tool-category artifact: {path}"


class TestVocabularyVersionMarker:
    """F0.4 — the freeze marker is a rendered series."""

    def test_the_gauge_renders_the_frozen_version(self) -> None:
        rendered = render_metrics()
        assert f"ensemble_metrics_vocabulary_version {VOCABULARY_VERSION}" in rendered

    def test_the_version_label_rides_only_the_current_release_gauge(self) -> None:
        assert VERSION_LABEL_POLICY == "current-release gauge only"
        rendered = render_metrics()
        version_series = [
            line
            for line in rendered.splitlines()
            if "vocabulary_version" in line and not line.startswith("#")
        ]
        assert version_series == [f"ensemble_metrics_vocabulary_version {VOCABULARY_VERSION}"]

    def test_the_frozen_vocabularies_render_next_to_the_gauge(self) -> None:
        rendered = render_metrics()
        assert "# frozen vocabulary instance_status:" in rendered
        assert "# frozen vocabulary sweep_lane:" in rendered
        assert "# frozen vocabulary mcp_roster:" in rendered
        assert "# frozen vocabulary tool_category:" in rendered
        assert "# frozen vocabulary version:" in rendered

    def test_bumping_the_version_is_a_deliberate_edit(self) -> None:
        """The version is an int (the bump contract's handle)."""
        assert isinstance(VOCABULARY_VERSION, int)
        assert VOCABULARY_VERSION >= 1


